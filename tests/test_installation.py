"""Installation treats standalone entry points and their helpers as one bundle."""

import argparse
import re
from pathlib import Path

import pytest

from threatlint import installation
from threatlint.cli import build_parser
from threatlint.skills import SKILLS, agent_prompt, agent_contracts, markdown_body, skill_map


@pytest.mark.parametrize("provider,directory,suffix", [
    ("claude", ".claude/agents", ".md"), ("copilot", ".github/agents", ".agent.md"),
])
def test_native_agent_install_includes_canonical_handoff_contracts(tmp_path, provider, directory, suffix):
    args = argparse.Namespace(local=True, directory=str(tmp_path), yes=True, quiet=True,
                              lmstudio=False, codex=False, copilot=provider == "copilot")
    assert installation.cmd_install(args) == 0
    if provider == "claude":
        assert (tmp_path / ".claude/agent-contracts.json").is_file()
    for agent, contract in agent_contracts().items():
        text = (tmp_path / directory / f"{agent}{suffix}").read_text(encoding="utf-8")
        assert contract["inputs"] in text
        assert contract["boundaries"] in text


def test_uninstall_removes_bundled_scripts_and_preserves_custom_content(tmp_path):
    args = argparse.Namespace(
        local=True, directory=str(tmp_path), yes=True, quiet=True,
        lmstudio=False, copilot=False,
    )
    assert installation.cmd_install(args) == 0
    scripts = tmp_path / ".claude" / "scripts"
    shipped = [path.name for path in installation._SCRIPTS_SRC.iterdir() if path.is_file()]
    assert "threatlint_chat.py" in shipped
    assert "_chat_content.py" in shipped
    assert "_appsec_prompts.py" in shipped
    assert all((scripts / name).is_file() for name in shipped)
    custom = scripts / "company-script.py"
    custom.write_text("# user-owned")
    nested = scripts / "company-tools"
    nested.mkdir()
    (nested / "notes.txt").write_text("user-owned")
    assert installation.cmd_uninstall(args) == 0
    assert not any((scripts / name).exists() for name in shipped)
    assert custom.read_text() == "# user-owned"
    assert (nested / "notes.txt").read_text() == "user-owned"


def _codex_args(tmp_path, *, local=True):
    return argparse.Namespace(
        local=local, directory=str(tmp_path), yes=True, quiet=True,
        codex=True, lmstudio=False, copilot=False,
    )


def test_codex_install_writes_complete_native_agent_skills(tmp_path):
    args = _codex_args(tmp_path)
    assert installation.cmd_install(args) == 0
    base = tmp_path / ".codex" / "skills"
    assert not (tmp_path / ".claude").exists()
    assert not (tmp_path / ".github").exists()

    agents = sorted(installation._AGENTS_SRC.glob("*.md"))
    assert len(agents) == len(skill_map())
    for source in agents:
        text = (base / source.stem / "SKILL.md").read_text(encoding="utf-8")
        header = re.match(r"^---\nname: ([^\n]+)\ndescription: (\"[^\n]+\")\n---\n", text)
        assert header, source.stem
        assert header.group(1) == source.stem
        assert header.group(2) == installation._frontmatter(source.read_text(encoding="utf-8"))["description"]
        assert "tools:" not in header.group(0)
        assert agent_prompt(source.stem, source) in text
        for skill in skill_map()[source.stem]:
            body = markdown_body((SKILLS / skill / "SKILL.md").read_text(encoding="utf-8"))
            assert body in text

    assert {folder.name for folder in base.iterdir()} == {source.stem for source in agents}
    fp_skill = (base / "appsec-fp-reviewer" / "SKILL.md").read_text(encoding="utf-8")
    assert "ServiceNow AVITs" in fp_skill.split("---", 2)[1]
    assert "threatlint run fp-review --provider codex --avit AVIT... --resolve-avits --yes" in fp_skill
    assert "threatlint run fp-review --provider codex --isst ISST... --resolve-avits --yes" in fp_skill
    assert "For a report-only AVIT review, omit `--resolve-avits --yes`" in fp_skill


def test_codex_reinstall_and_uninstall_preserve_unrelated_skills(tmp_path):
    args = _codex_args(tmp_path)
    assert installation.cmd_install(args) == 0
    base = tmp_path / ".codex" / "skills"
    agent = base / "appsec-threat-modeler" / "SKILL.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "\noutdated installation", encoding="utf-8")
    custom_skill = base / "company-workflow" / "SKILL.md"
    custom_skill.parent.mkdir()
    custom_skill.write_text("company workflow", encoding="utf-8")
    custom_note = agent.parent / "company-notes.md"
    custom_note.write_text("user-owned", encoding="utf-8")

    assert installation.cmd_install(args) == 0
    assert "Generated by threatlint install --codex" in agent.read_text(encoding="utf-8")
    assert "outdated installation" not in agent.read_text(encoding="utf-8")
    assert installation.cmd_uninstall(args) == 0
    assert not agent.exists()
    assert custom_note.read_text(encoding="utf-8") == "user-owned"
    assert custom_skill.read_text(encoding="utf-8") == "company workflow"


def test_codex_install_refuses_to_replace_user_skill(tmp_path):
    args = _codex_args(tmp_path)
    user_skill = tmp_path / ".codex" / "skills" / "appsec-threat-modeler" / "SKILL.md"
    user_skill.parent.mkdir(parents=True)
    user_skill.write_text("company instructions", encoding="utf-8")

    assert installation.cmd_install(args) == 1
    assert user_skill.read_text(encoding="utf-8") == "company instructions"
    assert not (tmp_path / ".codex" / "skills" / "appsec-fp-reviewer").exists()
    assert installation.cmd_uninstall(args) == 0
    assert user_skill.read_text(encoding="utf-8") == "company instructions"


@pytest.mark.parametrize("linked_path", [".codex", ".codex/skills"])
def test_codex_local_install_and_uninstall_reject_symlink_ancestors(tmp_path, linked_path):
    repo = tmp_path / "repo"
    repo.mkdir()
    outside = tmp_path / "outside"
    outside.mkdir()
    link = repo / linked_path
    link.parent.mkdir(parents=True, exist_ok=True)
    link.symlink_to(outside, target_is_directory=True)
    protected = outside / "sentinel.txt"
    protected.write_text("untouched", encoding="utf-8")

    args = _codex_args(repo)
    assert installation.cmd_install(args) == 1
    assert installation.cmd_uninstall(args) == 1
    assert protected.read_text(encoding="utf-8") == "untouched"
    assert {entry.name for entry in outside.iterdir()} == {"sentinel.txt"}


