def test_repo_local_codex_entry_points_resolve_to_canonical_protocols():
    root = Path(__file__).resolve().parents[1]
    for source in sorted(installation._AGENTS_SRC.glob("*.md")):
        entry = root / ".codex" / "skills" / source.stem / "SKILL.md"
        text = entry.read_text(encoding="utf-8")
        header = re.match(r"^---\nname: ([^\n]+)\ndescription: (\"[^\n]+\")\n---\n", text)
        assert header and header.group(1) == source.stem
        assert header.group(2) == installation._frontmatter(source.read_text(encoding="utf-8"))["description"]
        links = re.findall(r"\]\(([^)]+)\)", text)
        assert len(links) == 1 + len(skill_map()[source.stem])
        assert (entry.parent / links[0]).resolve() == source.resolve()
        for link, skill in zip(links[1:], skill_map()[source.stem]):
            assert (entry.parent / link).resolve() == (SKILLS / skill / "SKILL.md").resolve()
            assert (entry.parent / link).is_file()
    fp_skill = (root / ".codex" / "skills" / "appsec-fp-reviewer" / "SKILL.md").read_text(encoding="utf-8")
    assert "threatlint run fp-review --provider codex --avit AVIT... --resolve-avits --yes" in fp_skill
